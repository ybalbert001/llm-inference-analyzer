# ---------- pages & report data ----------

@app.get("/api/reports")
async def api_reports():
    with db() as conn:
        rows = conn.execute(
            "SELECT slug, model_id, lang, created_at, created_by, size_bytes,"
            " (SELECT COUNT(*) FROM access_log a"
            "   WHERE a.action='view' AND a.model_id = reports.model_id) AS views"
            " FROM reports ORDER BY created_at DESC"
        ).fetchall()
    return [dict(r) for r in rows]


@app.get("/reports/{slug}.html")
async def serve_report(request: Request, slug: str):
    if not re.match(r"^[a-z0-9_.-]+$", slug):
        raise HTTPException(400, "bad slug")
    username = current_user(request)
    if not username:
        # interstitial instead of auto-redirect: HF silently re-authorizes
        # already-approved apps, so an automatic bounce would undo /logout
        return HTMLResponse(LOGIN_GATE_HTML.replace("{next}", f"/reports/{slug}.html"),
                            status_code=401)
    path = REPORTS_DIR / f"{slug}.html"
    if not path.exists():
        raise HTTPException(404, "no such report")
    with db() as conn:
        row = conn.execute("SELECT model_id FROM reports WHERE slug=?", (slug,)).fetchone()
        conn.execute("UPDATE reports SET last_access=? WHERE slug=?", (now(), slug))
    log_access(username, "view", row["model_id"] if row else slug)
    return FileResponse(path, media_type="text/html")


@app.get("/", response_class=HTMLResponse)
async def index(request: Request):
    return templates.TemplateResponse(request, "index.html", {
        "username": current_user(request),
        "dev_mode": DEV_MODE,
    })


@app.get("/stats")
async def stats(request: Request):
    username = require_user(request)
    admins = [u.strip() for u in os.environ.get("ADMIN_USERS", "").split(",") if u.strip()]
    if admins and username not in admins:
        raise HTTPException(403, "admins only")
    with db() as conn:
        users = conn.execute(
            "SELECT username, COUNT(*) n, MAX(ts) last_seen FROM access_log"
            " GROUP BY username ORDER BY n DESC"
        ).fetchall()
        actions = conn.execute(
            "SELECT action, COUNT(*) n FROM access_log GROUP BY action"
        ).fetchall()
        recent = conn.execute(
            "SELECT ts, username, action, model_id FROM access_log"
            " ORDER BY id DESC LIMIT 50"
        ).fetchall()
    return JSONResponse({
        "users": [dict(r) for r in users],
        "actions": [dict(r) for r in actions],
        "recent": [dict(r) for r in recent],
    })


